import { TipoDocumento } from '@prisma/client';

export interface ClienteDemo {
  tipoDoc: TipoDocumento;
  numeroDoc: string;
  nome: string;
  email: string;
  telefone: string;
  logradouro: string;
  numero: string;
  complemento?: string;
  bairro: string;
  cidade: string;
  estado: string;
  cep: string;
}

export interface VeiculoDemo {
  placa: string;
  renavam: string;
  chassi: string;
  marca: string;
  modelo: string;
  ano: number;
  cor: string;
  quilometragem: number;
}

export interface PecaDemo {
  codigo: string;
  nome: string;
  descricao: string;
  precoVenda: string;
  quantidadeDisponivel: string;
  quantidadeMinima: string;
}

function cliente(
  tipoDoc: TipoDocumento,
  numeroDoc: string,
  nome: string,
  email: string,
  telefone: string,
  logradouro: string,
  numero: string,
  complemento: string | undefined,
  bairro: string,
  cidade: string,
  estado: string,
  cep: string,
): ClienteDemo {
  return {
    tipoDoc,
    numeroDoc,
    nome,
    email,
    telefone,
    logradouro,
    numero,
    complemento,
    bairro,
    cidade,
    estado,
    cep,
  };
}

function veiculo(
  placa: string,
  renavam: string,
  chassi: string,
  marca: string,
  modelo: string,
  ano: number,
  cor: string,
  quilometragem: number,
): VeiculoDemo {
  return {
    placa,
    renavam,
    chassi,
    marca,
    modelo,
    ano,
    cor,
    quilometragem,
  };
}

function peca(
  codigo: string,
  nome: string,
  descricao: string,
  precoVenda: string,
  quantidadeDisponivel: string,
  quantidadeMinima: string,
): PecaDemo {
  return {
    codigo,
    nome,
    descricao,
    precoVenda,
    quantidadeDisponivel,
    quantidadeMinima,
  };
}

