const {test,expect}=require('@playwright/test');
const {randomUUID}=require('node:crypto');
const h=require('./support.cjs');
const {portalUrl,desktopEvidence}=require('./browser-support.cjs');

test('consumo: resposta perdida mantém operação; excesso preserva saldo, foco e nova intenção',async({page},testInfo)=>{
  const pageErrors=[];page.on('pageerror',error=>pageErrors.push(error.message));
  const actors=await h.setup(),order=await h.prepare(actors,2,3,`consume-retry-${randomUUID()}`);
  await h.approve(actors,order);
  await page.goto(`${portalUrl}/#/login`);
  await page.getByRole('tab',{name:'Equipe',exact:true}).click();
  await page.locator('#operator-email').fill(actors.mechanicEmail);
  await page.locator('#operator-password').fill('Local-only-mechanic-password');
  await page.getByRole('button',{name:'Entrar como equipe',exact:true}).click();
  await expect(page).not.toHaveURL(/#\/login\/?$/);
  await page.goto(`${portalUrl}/#/ordens/${order.id}`);
  await page.getByRole('button',{name:'Iniciar execução',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Iniciar execução',exact:true}).click();
  await expect(page.getByRole('button',{name:'Consumir peça',exact:true})).toBeVisible({timeout:60000});
  await page.getByRole('button',{name:'Consumir peça',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'Registrar consumo de peça',exact:true});
  await dialog.getByRole('combobox',{name:/^Peça do orçamento/}).selectOption(order.pecaId);
  await dialog.getByLabel('Quantidade',{exact:true}).fill('1');
  const requests=[];let completedFirst,failedFirst;
  const firstDone=new Promise((resolve,reject)=>{completedFirst=resolve;failedFirst=reject;});
  firstDone.catch(()=>{});
  await page.route(`**/api/v1/ordens-servico/${order.id}/consumo-peca`,async route=>{
    requests.push(route.request().postDataJSON());
    if(requests.length===1) {
      try {
        const response=await route.fetch();
        expect(response.ok(),'The first consumption must commit before its response is lost').toBeTruthy();
        await route.abort('failed');completedFirst();
      } catch(error) { failedFirst(error);await route.abort('failed').catch(()=>{}); }
    } else await route.continue();
  });
  await dialog.getByRole('button',{name:'Registrar consumo',exact:true}).click();
  await firstDone;
  await expect(dialog.getByRole('button',{name:'Registrar consumo',exact:true})).toBeEnabled();
  await expect(dialog.getByRole('combobox',{name:/^Peça do orçamento/})).toBeDisabled();
  await expect(dialog.getByLabel('Quantidade',{exact:true})).toHaveAttribute('readonly','');
  await expect(dialog.getByRole('alert')).toContainText('sem duplicar o consumo');
  await expect(dialog.getByRole('alert')).toBeFocused();
  const consumed=await h.request('production',`/api/v1/production/orders/${order.id}`,actors.mechanic.accessToken);
  expect(consumed.parts[0].consumedQuantity).toBe(1);expect(consumed.parts[0].quantity).toBe(2);
  await desktopEvidence(page,testInfo,'consumption-retry-preserves-operation');
  // Reopening after reload must recover the pending operation without minting a new ID.
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Consumir peça',exact:true})).toBeFocused();
  await page.reload();
  await page.getByRole('button',{name:'Consumir peça',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Registrar consumo de peça',exact:true});
  await expect(dialog.getByRole('combobox',{name:/^Peça do orçamento/})).toHaveValue(order.pecaId);
  await expect(dialog.getByLabel('Quantidade',{exact:true})).toHaveValue('1');
  const retried=page.waitForResponse(response=>response.request().method()==='PATCH'&&new URL(response.url()).pathname.endsWith('/consumo-peca'));
  await dialog.getByRole('button',{name:'Registrar consumo',exact:true}).click();expect((await retried).ok()).toBeTruthy();
  await expect(dialog).toHaveCount(0);
  expect(requests).toHaveLength(2);expect(requests[1]).toEqual(requests[0]);expect(requests[0].operationId).toMatch(/^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}$/i);
  const after=await h.request('production',`/api/v1/production/orders/${order.id}`,actors.mechanic.accessToken);
  expect(after.revision).toBe(consumed.revision);expect(after.parts[0].consumedQuantity).toBe(1);
  const stock=await h.request('production',`/api/v1/production/inventory/${order.pecaId}?filialId=${order.filialId}`,actors.admin.accessToken);
  expect(stock.quantidadeDisponivel).toBe(1);expect(stock.quantidadeReservada).toBe(1);expect(stock.quantidadeConsumida).toBe(1);
  expect(pageErrors).toEqual([]);
  await testInfo.attach('consumption-idempotency',{body:Buffer.from(JSON.stringify({osId:order.id,operationId:requests[0].operationId,attempts:requests.length,revision:after.revision,consumed:after.parts[0].consumedQuantity,reserved:stock.quantidadeReservada})),contentType:'application/json'});
  // A definitive excess rejection keeps the aggregate and stock unchanged.
  await page.getByRole('button',{name:'Consumir peça',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Registrar consumo de peça',exact:true});
  await dialog.getByRole('combobox',{name:/^Peça do orçamento/}).selectOption(order.pecaId);
  await dialog.getByLabel('Quantidade',{exact:true}).fill('2');
  const excessResponse=page.waitForResponse(response=>response.request().method()==='PATCH'&&new URL(response.url()).pathname.endsWith('/consumo-peca'));
  await dialog.getByRole('button',{name:'Registrar consumo',exact:true}).click();
  const rejected=await excessResponse;
  expect(rejected.status()).toBe(400);
  const rejection=await rejected.json();
  expect(rejection).toMatchObject({code:'QUANTITY_EXCEEDS_RESERVATION',definitive:true,quantidadeSolicitada:2,quantidadeReservada:2,quantidadeConsumida:1,quantidadeRestante:1});
  const alert=dialog.getByRole('alert');
  await expect(alert).toContainText('Restam 1 unidade(s)');
  await expect(alert).toContainText('Corrija os dados antes de tentar novamente');
  await expect(alert).toBeFocused();
  await expect(dialog.locator('[data-consumption-balance]')).toHaveText('Reservada: 2 · Consumida: 1 · Restante: 1');
  await expect(dialog.getByRole('combobox',{name:/^Peça do orçamento/})).toBeEnabled();
  await expect(dialog.getByLabel('Quantidade',{exact:true})).not.toHaveAttribute('readonly','');
  expect(requests).toHaveLength(3);
  expect(requests[2].operationId).not.toBe(requests[0].operationId);
  const afterRejection=await h.request('production',`/api/v1/production/orders/${order.id}`,actors.mechanic.accessToken);
  expect(afterRejection).toEqual(after);
  expect(await h.request('production',`/api/v1/production/inventory/${order.pecaId}?filialId=${order.filialId}`,actors.admin.accessToken)).toEqual(stock);
  await desktopEvidence(page,testInfo,'consumption-excess-focused-with-balance');
  await page.keyboard.press('Tab');
  expect(await dialog.evaluate(element=>element.contains(document.activeElement))).toBe(true);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Consumir peça',exact:true})).toBeFocused();
  await testInfo.attach('consumption-definitive-rejection',{body:Buffer.from(JSON.stringify({osId:order.id,rejection,operationId:requests[2].operationId,revisionBefore:after.revision,revisionAfter:afterRejection.revision,focusReturnedToConsume:true})),contentType:'application/json'});
  // A separate intentional consumption must get a new operation ID and remain usable.
  await page.getByRole('button',{name:'Consumir peça',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Registrar consumo de peça',exact:true});
  await expect(dialog.getByRole('combobox',{name:/^Peça do orçamento/})).toBeEnabled();
  await expect(dialog.getByLabel('Quantidade',{exact:true})).not.toHaveAttribute('readonly','');
  await dialog.getByRole('combobox',{name:/^Peça do orçamento/}).selectOption(order.pecaId);
  await dialog.getByLabel('Quantidade',{exact:true}).fill('1');
  const secondUnit=page.waitForResponse(response=>response.request().method()==='PATCH'&&new URL(response.url()).pathname.endsWith('/consumo-peca'));
  await dialog.getByRole('button',{name:'Registrar consumo',exact:true}).click();expect((await secondUnit).ok()).toBeTruthy();
  await expect(dialog).toHaveCount(0);
  expect(requests).toHaveLength(4);expect(requests[3].operationId).not.toBe(requests[0].operationId);expect(requests[3].operationId).not.toBe(requests[2].operationId);
  const final=await h.request('production',`/api/v1/production/orders/${order.id}`,actors.mechanic.accessToken);
  expect(final.parts[0].consumedQuantity).toBe(2);expect(final.revision).toBe(after.revision+1);
  await page.getByRole('button',{name:'Finalizar serviço',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Finalizar serviço',exact:true}).click();
  await expect(page.locator('.page-header .status-badge')).toContainText('Aguardando pagamento',{timeout:60000});
  expect(pageErrors).toEqual([]);
});
